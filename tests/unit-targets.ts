import { interpretRequest } from "../lib/intent";
import { applyEffectToAdjust, EFFECTS } from "../lib/effects";
import { zeroAdjust } from "../lib/masks";
let pass = 0, fail = 0; const ok = (n: string, c: boolean, i = "") => { c ? pass++ : fail++; console.log(`${c ? "PASS" : "FAIL"}  ${n}${i ? "  [" + i + "]" : ""}`); };
const r = interpretRequest("Darken the leaves, sharpen the ants, preserving the sunlight brightness");
const f = r.layers.find((l) => l.target === "foliage"), s = r.layers.find((l) => l.target === "subject");
ok("leaves -> foliage mask with negative exposure", !!f && (f.adjust.exposure ?? 0) < 0, JSON.stringify(f?.adjust));
ok("ants -> subject mask with sharpen", !!s && (s.adjust.sharpen ?? 0) > 0, JSON.stringify(s?.adjust));
ok("'preserving the sunlight' protects bright areas on the masks", !!f?.limitHighlights && !!s?.limitHighlights);
ok("nothing from that sentence went to a global edit", r.ops.length === 0, r.ops.map((o) => o.key).join());
ok("the subject mask carries an honest caveat", /not a pixel-accurate/i.test(s?.caveat ?? ""));
ok("preserve clause is not reported as 'not understood'", r.unmatched.length === 0, r.unmatched.join("|"));
const g = interpretRequest("warmer, and brighten the shadows, blur the background");
ok("plain global words stay global", g.ops.some((o) => o.key === "warmer"));
ok("'brighten the shadows' stays the global shadows rule, not a mask... or a shadows mask", g.layers.length + g.ops.length >= 2);
ok("background blur keeps the bokeh effect", g.ops.some((o) => o.key === "bokeh"));
const e = applyEffectToAdjust(zeroAdjust(), EFFECTS.find((x) => x.id === "gaussian-blur")!, 1);
ok("effect on a mask: gaussian blur lands in blur", (e.adjust.blur ?? 0) > 30);
const c = applyEffectToAdjust(zeroAdjust(), EFFECTS.find((x) => x.id === "black-white")!, 1);
ok("frame-wide effects are skipped on masks and reported", c.skipped.includes("black & white"));
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
